import base64
import unittest
from datetime import date
from unittest.mock import patch

import numpy as np
import pandas as pd

from analysis.report import _zone_rows, generate_scouting_report


class ScoutingReportTests(unittest.TestCase):
    def test_zone_rows_separate_ability_and_agent_names(self):
        zones = pd.DataFrame([{
            "site_label": "B site", "ability_name": "Shear", "agent": "vyse",
            "player_name": "OXY", "rounds_used": 1234, "total_rounds": 2500,
            "percentage": 49.36, "series_count": 12,
        }])

        markup = _zone_rows(zones, "defense", "Lotus")

        self.assertIn("<b>B site</b><span class='ability-name'>Shear</span>", markup)
        self.assertIn("<b>Agent:</b> Vyse", markup)
        self.assertIn("1,234/2,500 defense rounds (49%), 12 series", markup)
        self.assertNotIn("ShearVyse", markup)
    @staticmethod
    def _fixtures():
        rounds = pd.DataFrame([
            {
                "series_id": "series-1", "game_id": "game-1", "round_number": number,
                "team_id": "team-1", "team_name": "Team <A>", "map": "Lotus",
                "side": "defender", "round_start_time": f"2025-01-0{number}T12:00:00Z",
            }
            for number in (1, 2)
        ])
        casts = pd.DataFrame([
            {
                "series_id": "series-1", "game_id": "game-1", "round_number": number,
                "team_id": "team-1", "map": "Lotus", "side": "defender", "player_id": "secret-player-id",
                "player_name": "A<&", "agent": "killjoy", "ability": "nanoswarm",
                "seconds_into_round": -2, "x": 100.0 + number, "y": 100.0,
                "landing_x": 105.0 + number, "landing_y": 100.0,
            }
            for number in (1, 2)
        ])
        buys = pd.DataFrame([
            {
                "series_id": "series-1", "game_id": "game-1", "round_number": number,
                "team_id": "team-1", "map": "Lotus", "side": "defender", "player_id": "secret-player-id",
                "player_name": "A<&", "agent": "killjoy", "has_operator": number == 1,
            }
            for number in (1, 2)
        ])
        tables = {
            "rounds": rounds,
            "casts": casts.assign(private_event_payload="never include this"),
            "buys": buys,
            "kills": pd.DataFrame(),
            "damage": pd.DataFrame(),
            "spawn_positions": pd.DataFrame(),
        }
        shapes = {
            "lotus": {
                "map": "Lotus", "density": np.ones((5, 5)),
                "x": np.linspace(0, 1600, 5), "y": np.linspace(0, 1600, 5),
                "x_min": 0.0, "x_max": 1600.0, "y_min": 0.0, "y_max": 1600.0,
            },
        }
        sites = {"lotus": {"A": {"x": 100.0, "y": 100.0, "plant_count": 4}}}
        return tables, shapes, sites

    def test_report_is_standalone_a4_html_with_aggregate_image_and_escaped_values(self):
        tables, shapes, sites = self._fixtures()
        cards = [{
            "tendency": "Expect utility <b>here</b>", "confidence": "High",
            "facts": ["2/2 rounds (100%)"], "response": "Do not dry-peek <script>.",
        }]
        with patch("analysis.report.generate_counter_plan", return_value={"cards": cards, "watch_list": []}):
            report = generate_scouting_report(
                tables, "Team <A>", "team-1", "All maps", "defense", "defender", shapes, sites,
                image_exporter=lambda figure: b"png fixture", generated_on=date(2026, 1, 1),
            )

        self.assertIn("@page { size: A4 portrait", report)
        self.assertIn("data:image/png;base64," + base64.b64encode(b"png fixture").decode(), report)
        self.assertIn("Team &lt;A&gt; · Scouting Report", report)
        self.assertIn("2025-01-01 – 2025-01-02", report)
        self.assertIn("Most-played map", report)
        self.assertIn("GRID official esports data · generated by Scout Sheet", report)
        self.assertIn("Expect utility &lt;b&gt;here&lt;/b&gt;", report)
        self.assertIn("Do not dry-peek &lt;script&gt;.", report)
        self.assertIn("A&lt;&amp;", report)
        self.assertNotIn("<li><b>1.", report)
        self.assertNotIn("secret-player-id", report)
        self.assertNotIn("never include this", report)
        self.assertNotIn("<script>", report)


if __name__ == "__main__":
    unittest.main()